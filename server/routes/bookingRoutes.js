const express = require('express');
const mongoose = require('mongoose');
const authenticate = require('../middleware/authenticate');
const authorize = require('../middleware/authorize');
const HttpError = require('../utils/HttpError');
const actions = require('../controllers/bookingScheduleController');
const payments = require('../services/paymentService');
const receipts = require('../services/receiptService');
const invoices = require('../services/invoiceService');
const additionalWork = require('../services/additionalWorkService');
const { uploadProof } = require('../middleware/imageUpload');
const credentialEmails = require('../middleware/rateLimit')({ limit: 20, windowMs: 15 * 60 * 1000 });

const router = express.Router();
router.use((req, res, next) => {
  res.set('Cache-Control', 'no-store');
  if (mongoose.connection.readyState !== 1) return next(new HttpError(503, 'Database is temporarily unavailable.'));
  next();
});
router.use(authenticate, authorize('client', 'staff', 'admin'));
router.get('/availability', actions.bookingAvailability);
router.get('/options', authorize('client'), actions.bookingOptions);
router.get('/active-services', authorize('client'), actions.activeServiceIds);
router.get('/walk-in/options', authorize('staff', 'admin'), actions.walkInOptions);
router.get('/walk-in/email-check', authorize('staff', 'admin'), actions.walkInEmailCheck);
router.post('/walk-in/client-account', authorize('staff', 'admin'), credentialEmails, actions.walkInClientAccount);
router.post('/walk-in/visit', authorize('staff', 'admin'), actions.walkInVisit);
router.get('/assignment-options', authorize('staff', 'admin'), actions.assignmentOptions);
router.get('/walk-in/clients', authorize('staff', 'admin'), actions.walkInClients);
router.get('/walk-in/clients/:clientId/vehicles', authorize('staff', 'admin'), actions.walkInVehicles);
router.post('/walk-in/clients/:clientId/vehicles', authorize('staff', 'admin'), actions.walkInVehicleCreate);
router.post('/walk-in/clients/:clientId/resend-credentials', authorize('staff', 'admin'), credentialEmails, actions.resendClientCredentials);
router.post('/walk-in', authorize('staff', 'admin'), actions.walkInCreate);
router.post('/walk-in/new-client', authorize('staff', 'admin'), actions.newWalkInCreate);
router.get('/', actions.bookingList);
router.post('/', authorize('client'), actions.bookingCreate);
router.get('/:id', actions.bookingGet);
router.post('/:id/cancel', authorize('client', 'staff', 'admin'), actions.bookingCancel);
router.post('/:id/confirm', authorize('staff', 'admin'), actions.bookingConfirm);
router.post('/:id/reject', authorize('staff', 'admin'), actions.bookingReject);
router.post('/:id/check-in', authorize('staff', 'admin'), actions.bookingCheckIn);
router.post('/:id/no-show', authorize('staff', 'admin'), actions.bookingNoShow);
router.post('/:id/assign', authorize('staff', 'admin'), actions.bookingAssign);
router.post('/:id/reschedule', authorize('staff', 'admin'), actions.bookingReschedule);
router.get('/:id/payment', authorize('client', 'staff', 'admin'), async (req, res) => res.json({ item: await payments.summary(req.params.id, req.user) }));
router.get('/:id/receipts', authorize('client', 'staff', 'admin'), async (req, res) => res.json({ items: await receipts.list(req.params.id, req.user) }));
router.get('/:id/invoices', authorize('client', 'staff', 'admin'), async (req, res) => res.json({ items: await invoices.list(req.params.id, req.user) }));
router.get('/:id/additional-work', authorize('client', 'staff', 'admin'), async (req, res) => res.json({ items: await additionalWork.list(req.params.id, req.user) }));
router.post('/:id/payments', authorize('client', 'staff', 'admin'),
  async (req, res, next) => { await payments.assertAccess(req.params.id, req.user); next(); },
  uploadProof, async (req, res) => res.status(201).json({ item: await payments.submit(req.params.id, req.user, req.body, req.file) }));
router.post('/:id/payments/:paymentId/verify', authorize('staff', 'admin'), async (req, res) => res.json({ item: await payments.decide(req.params.id, req.params.paymentId, req.user, 'verify') }));
router.post('/:id/payments/:paymentId/reject', authorize('staff', 'admin'), async (req, res) => res.json({ item: await payments.decide(req.params.id, req.params.paymentId, req.user, 'reject') }));
module.exports = router;
