const express = require('express');
const mongoose = require('mongoose');
const authenticate = require('../middleware/authenticate');
const authorize = require('../middleware/authorize');
const HttpError = require('../utils/HttpError');
const actions = require('../controllers/bookingScheduleController');
const credentialEmails = require('../middleware/rateLimit')({ limit: 20, windowMs: 15 * 60 * 1000 });

const router = express.Router();
router.use((req, res, next) => {
  res.set('Cache-Control', 'no-store');
  if (mongoose.connection.readyState !== 1) return next(new HttpError(503, 'Database is temporarily unavailable.'));
  next();
});
router.use(authenticate, authorize('client', 'staff', 'admin'));
router.get('/availability', actions.bookingAvailability);
router.get('/options', authorize('client'), actions.bookingOptions);
router.get('/active-services', authorize('client'), actions.activeServiceIds);
router.get('/walk-in/options', authorize('staff'), actions.walkInOptions);
router.get('/walk-in/email-check', authorize('staff'), actions.walkInEmailCheck);
router.get('/assignment-options', authorize('staff'), actions.assignmentOptions);
router.get('/walk-in/clients', authorize('staff'), actions.walkInClients);
router.get('/walk-in/clients/:clientId/vehicles', authorize('staff'), actions.walkInVehicles);
router.post('/walk-in/clients/:clientId/vehicles', authorize('staff'), actions.walkInVehicleCreate);
router.post('/walk-in/clients/:clientId/resend-credentials', authorize('staff'), credentialEmails, actions.resendClientCredentials);
router.post('/walk-in', authorize('staff'), actions.walkInCreate);
router.post('/walk-in/new-client', authorize('staff'), actions.newWalkInCreate);
router.get('/', actions.bookingList);
router.post('/', authorize('client'), actions.bookingCreate);
router.get('/:id', actions.bookingGet);
router.post('/:id/cancel', authorize('client', 'staff'), actions.bookingCancel);
router.post('/:id/confirm', authorize('staff'), actions.bookingConfirm);
router.post('/:id/reject', authorize('staff'), actions.bookingReject);
router.post('/:id/check-in', authorize('staff'), actions.bookingCheckIn);
router.post('/:id/assign', authorize('staff'), actions.bookingAssign);
router.post('/:id/reschedule', authorize('staff'), actions.bookingReschedule);
module.exports = router;
